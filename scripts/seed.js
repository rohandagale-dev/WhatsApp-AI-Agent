/**
 * Seeds demo personas, contacts and per-contact AI configuration.
 *
 * Persona text lives in relation_persons (my_persona / style / rules), which is
 * what services/promptService.js actually reads. The personas table itself only
 * holds id, name, is_active, created_at.
 *
 * style / rules are written ONLY when my_persona does not already define those
 * sections itself -- see resolveSections() below for why.
 *
 *   node scripts/seed.js
 */
require('../loadEnv');
const { supabase } = require('../services/supabaseClient');
// Same source of truth services/trainingService.js uses, so the demo contact
// behaves like the real agent instead of a generic assistant.
const { loadSystemPrompt } = require('../services/systemPrompt');

const rohanPrompt = loadSystemPrompt();

// personas.name has no UNIQUE constraint, so upsert-on-name is not available.
// Look the row up first and insert only when missing. Ids are never hardcoded:
// the column is GENERATED BY DEFAULT AS IDENTITY, and supplying explicit values
// does not advance the sequence, which eventually collides on personas_pkey.
async function ensurePersona(name) {
    const { data: found, error: findErr } = await supabase
        .from('personas').select('*').eq('name', name).limit(1);
    if (findErr) throw findErr;
    if (found && found.length) return found[0];

    const { data, error } = await supabase
        .from('personas').insert({ name }).select().single();
    if (error) throw error;
    console.log(`  created persona "${name}" (id=${data.id})`);
    return data;
}

async function ensureContact({ phone, name, notes, persona }) {
    const { data, error } = await supabase.from('contacts')
        .upsert({ phone, name, notes, persona_id: persona.id }, { onConflict: 'phone' })
        .select().single();
    if (error) throw error;
    return data;
}

/**
 * True when the persona text defines the named section itself.
 *
 * Matches the markdown headings used by system_prompt_v2/v3 ("## Style",
 * "## Rules") and the plain-text headings used by system_prompt_v1
 * ("TONE & STYLE:", "RULES:"). A heading is a whole line: an optional run of
 * '#', optional leading words ("TONE & "), the section name, an optional colon.
 * That keeps prose such as "match the user's style" from counting as a section.
 */
function carriesOwnSection(personaText, section) {
    if (typeof personaText !== 'string' || !personaText) return false;
    const heading = new RegExp(
        `^[ \\t]*(?:#{1,6}[ \\t]*)?[A-Za-z&' \\t-]*\\b${section}\\b[ \\t]*:?[ \\t]*$`,
        'im'
    );
    return heading.test(personaText);
}

/**
 * Decides which of style / rules may be written for a seed entry.
 *
 * promptService renders relation_persons.style and .rules as their own STYLE:
 * and RULES: blocks. A my_persona lifted out of system_prompts/*.txt ALREADY
 * carries its own "## Style" and "## Rules" sections, so filling those columns
 * too puts two competing rule sets in a single prompt -- same intent, different
 * wording -- and the model splits the difference and sounds like neither. When
 * the persona defines a section itself the column is left NULL, and
 * promptService then omits that block entirely (an absent section beats a
 * contradicting one).
 *
 * Personas that are a one-line assistant description define no sections, so
 * they keep their seeded style/rules -- that is the only guidance those
 * contacts get.
 *
 * The test is on the persona TEXT, never on which contact it is, so swapping
 * SYSTEM_PROMPT_VERSION or handing a different contact a full prompt file does
 * the right thing without editing this file.
 */
function resolveSections({ myPersona, style, rules }) {
    return {
        style: carriesOwnSection(myPersona, 'style') ? null : style,
        rules: carriesOwnSection(myPersona, 'rules') ? null : rules
    };
}

async function ensureRelation(contact, entry) {
    const { myPersona, dictionary, userPersona } = entry;
    // Written as explicit NULLs rather than omitted keys: the upsert has to
    // clear style/rules on rows an earlier run of this script already filled in.
    const sections = resolveSections(entry);

    const { error } = await supabase.from('relation_persons').upsert({
        contact_id: contact.id,
        my_persona: myPersona,
        style: sections.style,
        rules: sections.rules,
        my_dictionary: dictionary,
        user_persona: userPersona
    }, { onConflict: 'contact_id' });
    if (error) throw error;

    return sections;
}

