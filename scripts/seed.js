async function main() {
    console.log(`Seeding database (system prompt: ${rohanPrompt.version})...`);

    const personaCache = new Map();
    for (const entry of SEED) {
        if (!personaCache.has(entry.personaName)) {
            personaCache.set(entry.personaName, await ensurePersona(entry.personaName));
        }
        const persona = personaCache.get(entry.personaName);

        const contact = await ensureContact({
            phone: entry.phone,
            name: entry.name,
            notes: entry.notes,
            persona: persona
        });
        const sections = await ensureRelation(contact, entry);

        console.log(`  contact ${entry.phone} -> persona "${entry.personaName}" (id=${contact.id})`);

        const dropped = ['style', 'rules'].filter(name => entry[name] && !sections[name]);
        if (dropped.length) {
            console.log(`    my_persona defines its own ${dropped.join(' and ')} section(s); ` +
                `left relation_persons.${dropped.join('/.')} NULL to avoid a second, competing rule set`);
        }
    }

    console.log('Seeding complete!');
}

main().catch((e) => {
    console.error('Seed failed:', e.message || e);
    process.exit(1);
});
